//! GenerationSet.Lifecycle.cs: makes protoc's classes acceptable to Unity
//! 6000.5 and newer, whose lifecycle analyzer (UAL0010 / UAL0013) wants every
//! type holding static fields marked `[AutoStaticsCleanup]` or
//! `[NoAutoStaticsCleanup]` (Unity.Scripting.LifecycleManagement).
//!
//! protoc's classes hold static, immutable state: the file descriptor and
//! each message's parser, built once and valid for the whole process, so
//! `NoAutoStaticsCleanup`. protoc's file must not be edited, but each of its
//! classes is `partial`, so the attribute goes on a second part of the same
//! class, in a file of its own, written from the declarations protoc wrote
//! (same modifiers, so the parts agree). A message added to the .proto is
//! picked up on the next run.
//!
//! The whole file is inside `#if LIFECYCLE_APIS_AVAILABLE`, which the
//! package's runtime asmdef defines for Unity 6000.5 or newer (its
//! versionDefines), so older editors compile it to nothing.

use crate::error::{app_error::AppError, app_result::AppResult};

/// The define the file is guarded by. It must be the `define` of the
/// versionDefines entry in
/// unity/packages/simulation.cart-pole.synthetic-data-gen/Runtime/Simulation.CartPole.SyntheticDataGen.Runtime.asmdef
/// (`{"name": "Unity", "expression": "6000.5", "define": ...}`), which is
/// what sets it on Unity 6000.5 and newer.
const LIFECYCLE_DEFINE: &str = "LIFECYCLE_APIS_AVAILABLE";

/// The attribute Unity's lifecycle analyzer accepts for statics that live for
/// the whole process (Unity.Scripting.LifecycleManagement).
const NO_CLEANUP_ATTRIBUTE: &str = "[NoAutoStaticsCleanup]";

/// The namespace NO_CLEANUP_ATTRIBUTE is in, as the file imports it.
const LIFECYCLE_USING: &str = "using Unity.Scripting.LifecycleManagement;";

/// The file's opening comment: the `<auto-generated>` block (so C# tools
/// treat it as generated and skip their style checks) and why it exists.
const HEADER: &str = "// <auto-generated>
//     Generated by `cargo run -p generator --bin generate-csharp` from
//     the classes in GenerationSet.cs. DO NOT EDIT!
// </auto-generated>
// Marks protoc's classes for Unity 6000.5+'s lifecycle analyzer: their
// statics are a descriptor and parsers built once for the whole process.
";

/// How protoc's C# opens its namespace: `namespace <Name> {`.
const NAMESPACE_PREFIX: &str = "namespace ";
const NAMESPACE_SUFFIX: &str = " {";

/// The words that end each class declaration protoc writes, e.g.
/// `  public sealed partial class Range : pb::IMessage<Range>`.
const PARTIAL_CLASS: &str = "partial class ";

/// The modifiers protoc writes before `partial class`: an access modifier,
/// then `static` for the reflection holder or `sealed` for a message.
const ACCESS_MODIFIERS: [&str; 2] = ["public", "internal"];
const CLASS_MODIFIERS: [&str; 2] = ["static", "sealed"];

/// The text of GenerationSet.Lifecycle.cs for protoc's `generated` source:
/// one `[NoAutoStaticsCleanup]` part per class declaration in it, in the
/// same namespace and with the same modifiers.
pub(crate) fn lifecycle_source(generated: &str) -> AppResult<String> {
    let namespace = generated
        .lines()
        .find_map(|line| {
            line.strip_prefix(NAMESPACE_PREFIX)
                .and_then(|rest| rest.strip_suffix(NAMESPACE_SUFFIX))
        })
        .ok_or_else(|| AppError::generated("no `namespace <Name> {` line in protoc's output"))?;

    let classes: Vec<String> = generated
        .lines()
        .filter_map(class_declaration)
        .map(|(modifiers, name)| {
            format!("    {NO_CLEANUP_ATTRIBUTE}\n    {modifiers} partial class {name} {{ }}")
        })
        .collect();
    if classes.is_empty() {
        return Err(AppError::generated(
            "no partial class declarations in protoc's output",
        ));
    }

    let body = classes.join("\n\n");
    Ok(format!(
        "{HEADER}#if {LIFECYCLE_DEFINE}\n{LIFECYCLE_USING}\n\nnamespace {namespace}\n{{\n{body}\n}}\n#endif\n"
    ))
}

/// A line protoc writes to declare a class, as (modifiers, name): e.g.
/// `  public sealed partial class Range : pb::IMessage<Range>` gives
/// ("public sealed", "Range"). Any other line gives None.
fn class_declaration(line: &str) -> Option<(String, &str)> {
    let line = line.trim_start();
    let at = line.find(PARTIAL_CLASS)?;
    let modifiers: Vec<&str> = line.get(..at)?.split_whitespace().collect();
    let (access, rest) = modifiers.split_first()?;
    if !ACCESS_MODIFIERS.contains(access)
        || rest.len() > 1
        || rest
            .first()
            .is_some_and(|modifier| !CLASS_MODIFIERS.contains(modifier))
    {
        return None;
    }
    let after = line.get(at + PARTIAL_CLASS.len()..)?;
    let name_end = after
        .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
        .unwrap_or(after.len());
    let name = after.get(..name_end)?;
    if name.is_empty() {
        return None;
    }
    Some((modifiers.join(" "), name))
}
